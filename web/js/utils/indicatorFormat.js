/**
 * تنسيق موحّد لعرض معدل العائد الداخلي (IRR) — مصدر حقيقة واحد لدلالة القيمة غير
 * المحقّقة، تنفيذاً لسياسة «الأرقام الأمينة».
 *
 * الخلفية (تدقيق جولة الموقع 2026-07-20، بندا #1 و#13): لوحة القرار تعرض IRR غير
 * المحقّق كـ«غير محقق»/«غير قابل للحساب»، بينما لوحة المستثمر وتقرير البنك وعرض
 * العرض ورسالة المشاركة كانوا يعرضونه «0.0%» عبر النمط الخاطئ `(irr||0)*100` — تعارض
 * في معنى البيانات لا مجرد تنسيق. ملاحظة: `SAFE.pct` في web/export/utils.js يُرجع 0
 * للقيمة الغائبة (رقمياً) فلا يصلح لهذه الحالة، لذا هذا المُنسّق منفصل ومقصود.
 */

/** IRR (كسر من المحرك، 0.28 → «28.0%»)؛ غير محقّق (null/غير منتهٍ) → «غير محقق». */
export function formatIrrPct(irr, digits = 1) {
    return (irr == null || !Number.isFinite(Number(irr)))
        ? 'غير محقق'
        : (Number(irr) * 100).toFixed(digits) + '%';
}
