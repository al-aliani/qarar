/**
 * إرجاع شرح الحقل { help, example } — تطابق كامل أولاً ثم الجزء الأخير من المفتاح، أو null.
 */
export function getFieldHelp(key) {
    if (!key) return null;
    const k = String(key).split('.').pop();
    return FIELD_HELP_TEXTS[key] ?? FIELD_HELP_TEXTS[k] ?? null;
}
