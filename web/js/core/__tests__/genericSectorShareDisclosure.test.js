/**
 * تدقيق 2026-09-04 — رحلة عميل صالون حلاقة: بطاقة «اقتراح من بيانات هيئة الإحصاء»
 * اقترحت TAM = ١٥٫١ مليار ريال/سنة لصالون في الرياض. بقسمة الرقم على السكان
 * (٧٬٦٧٦٬٦٥٤) ينتج ١٬٩٧٠ ريالاً للفرد سنوياً على الحلاقة — بعيد جداً عن الواقع.
 *
 * السبب: جدول sectorConsumptionShare يضمّ 20 مفتاحاً قطاعياً، ولا مفتاح فيه
 * للصالونات ولا المغاسل ولا النوادي الرياضية ولا مراكز الصيانة — فتسقط كلها على
 * default = 2٪ بلا أن يعلم المستخدم أن الرقم عام لا خاص بنشاطه.
 *
 * القرار المتعمَّد: **لم نخترع نسبة بديلة.** كل هذه النسب تقديرية بلا مصدر منشور
 * (موسومة ASSUMPTION حيثما تُعرض)، واستبدال تقدير بتقدير لا يزيد صدقاً ويوهم بدقة
 * لا نملكها. الإصلاح هو الإفصاح: يعرف العميل أن قطاعه بلا مدخل خاص فيراجع الرقم.
 */
import { describe, it, expect } from 'vitest';
import { resolveSectorShare, isGenericSectorShare } from '../marketSizingModel.js';

describe('نسبة استهلاك القطاع: الإفصاح عن استخدام النسبة العامة', () => {
    it.each([
        'صالون / مركز تجميل',
        'مغسلة ملابس',
        'رياضة ولياقة / صالة رياضية',
        'صيانة وتنظيف',
    ])('«%s» بلا مدخل خاص ⟶ يُبلَّغ عنه كنسبة عامة', (sector) => {
        expect(isGenericSectorShare(sector)).toBe(true);
    });

    it.each([
        ['مطعم', 0.025],
        // «صحي» معرَّف قبل «عيادة» في الجدول وأول مطابقة تفوز — 0.04 لا 0.035
        ['رعاية صحية / عيادة', 0.04],
        ['تعليم وتدريب', 0.03],
        ['متجر تجزئة / بقالة / سوبرماركت', 0.05],
    ])('«%s» له مدخل خاص فلا يُبلَّغ عنه كعام', (sector, expectedShare) => {
        expect(isGenericSectorShare(sector)).toBe(false);
        expect(resolveSectorShare(sector)).toBe(expectedShare);
    });

    it('النشاط الفارغ يُعامل كعام', () => {
        expect(isGenericSectorShare('')).toBe(true);
        expect(isGenericSectorShare(null)).toBe(true);
    });

    it('الكاشف متسق مع القيمة المُعادة — كل «عام» يعيد النسبة الافتراضية', () => {
        for (const sector of ['صالون / مركز تجميل', 'مغسلة ملابس', 'نشاط غير معروف إطلاقاً']) {
            expect(isGenericSectorShare(sector)).toBe(true);
            expect(resolveSectorShare(sector)).toBe(0.02);
        }
    });

    it('لا يغيّر أي نسبة قائمة — الإصلاح إفصاح لا تعديل أرقام', () => {
        expect(resolveSectorShare('صالون / مركز تجميل')).toBe(0.02);
        expect(resolveSectorShare('مطعم')).toBe(0.025);
    });
});
