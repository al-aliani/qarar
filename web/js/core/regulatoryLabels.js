/**
 * إرجاع التسمية المتوافقة مع نماذج بنك التنمية الاجتماعية
 */
export function getLabelSDB(key, fallback) {
    const k = (key || '').split('.').pop();
    return LABELS_SDB[k] ?? LABELS_SDB[key] ?? fallback ?? getLabel(key) ?? key;
}

/**
 * إرجاع تلميح المدقق المالي للحقل (للعرض في Tooltip)
 */
